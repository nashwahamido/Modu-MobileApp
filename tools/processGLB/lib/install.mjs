export function emitAuthored(draft, extras) {
  const L = [];
  L.push(`// GENERATED by tools/processGLB — starting point; refine against the manual`);
  L.push(`// (seeds, slide/screw intent, stages, requires, beats), then iterate with:`);
  L.push(`//   npm run furniture:validate ${draft.id} && npm run furniture:test ${draft.id}`);
  L.push(`import { action, FastenerRule } from "@/src/game/core/composition/composeActions";`);
  L.push(`import { StructureOverlay } from "@/src/game/core/model/liaisons";`);
  L.push(`import { asGroupId } from "@/src/game/core/ids";`);
  L.push(`import { ClusterDef, ClusterId, DraftAction, InstructionSet, LabelMap } from "@/src/game/core/type";`);
  L.push(``);
  L.push(`export const META = {`);
  L.push(`  name: ${JSON.stringify(draft.meta.name)},`);
  L.push(`  brand: ${JSON.stringify(extras.brand ?? "IKEA")},`);
  L.push(`  category: ${JSON.stringify(extras.category ?? "Other")},`);
  L.push(`  difficulty: ${draft.meta.difficulty},`);
  L.push(`  duration: ${draft.meta.duration},`);
  L.push(`  link: ${JSON.stringify(extras.link ?? "")},`);
  L.push(`} as const;`);
  L.push(``);
  L.push(`export const LABELS = {`);
  for (const [g, label] of Object.entries(draft.labels))
    L.push(`  ${g}: { standard: ${JSON.stringify(label)} },`);
  L.push(`} as LabelMap;`);
  L.push(``);
  L.push(`export const CLUSTERS = {`);
  for (const c of draft.clusters)
    L.push(`  ${c.id}: { id: ${JSON.stringify(c.id)}, label: ${JSON.stringify(c.label)} },`);
  L.push(`} as Record<ClusterId, ClusterDef>;`);
  L.push(``);
  L.push(`export const STRUCTURE: StructureOverlay = {`);
  const seeds = new Set(draft.placements.filter((p) => p.stage === 1 && p.requires.length === 0)
    .reduce((acc, p) => { if (!acc.some((q) => q.cluster === p.cluster)) acc.push(p); return acc; }, [])
    .map((p) => p.partId));
  const joinsByLater = new Map();
  for (const j of draft.joints.filter((j) => !j.crossCluster))
    (joinsByLater.get(j.later) ?? joinsByLater.set(j.later, []).get(j.later))
      .push(j.later === j.a ? j.b : j.a);
  for (const p of draft.placements) {
    const fields = [];
    if (seeds.has(p.partId)) fields.push("seed: true");
    const dj = joinsByLater.get(p.partId);
    if (dj?.length) fields.push(`directJoins: [${dj.map((x) => JSON.stringify(x)).join(", ")}]`);
    L.push(`  ${p.partId}: { ${fields.join(", ")}${fields.length ? " " : ""}},`);
  }
  L.push(`} as StructureOverlay;`);
  L.push(``);
  L.push(`export const FASTENER_RULES: FastenerRule[] = [`);
  for (const r of draft.rules)
    L.push(`  { group: asGroupId(${JSON.stringify(r.group)}), stage: ${r.stage} },`);
  L.push(`];`);
  L.push(``);
  L.push(`export const AUTHORED_ACTIONS: DraftAction[] = [`);
  for (const p of draft.placements)
    L.push(`  action({ type: "placePart", stage: ${p.stage}, partId: ${JSON.stringify(p.partId)}, requires: ${JSON.stringify(p.requires)} }),`);
  const multi = draft.clusters.length > 1;
  if (multi)
    for (const c of draft.clusters.slice(1))
      L.push(`  action({ actionId: "combine_${c.id}", type: "combineClusters", stage: ${draft.maxStage + 1}, cluster: ${JSON.stringify(c.id)}, requires: [] }),`);
  L.push(`  action({ actionId: "finishing_checks", type: "reorient", stage: ${draft.maxStage + 1}, requires: [${multi ? draft.clusters.slice(1).map((c) => JSON.stringify("combine_" + c.id)).join(", ") : ""}] }),`);
  L.push(`];`);
  L.push(``);
  L.push(`export const BEATS = {} as InstructionSet;`);
  return L.join("\n") + "\n";
}

