export function patchFurnitureId(src, id) {
  if (new RegExp(`"${id}"`).test(src)) throw new Error(`FurnitureId already contains "${id}"`);
  const re = /(export type FurnitureId =\s*(?:"[^"]+"\s*\|\s*)*"[^"]+")(;)/;
  if (!re.test(src)) throw new Error("FurnitureId anchor not found in type.ts");
  return src.replace(re, `$1 | "${id}"$2`);
}

export function patchFurnituresTs(src, id) {
  if (src.includes(`${id}_META`)) throw new Error(`furnitures.ts already registers ${id}`);
  let out = src.replace(/(import { \w+_META } from "\.\/\w+\/meta";)(?![\s\S]*import { \w+_META })/,
    `$1\nimport { ${id}_META } from "./${id}/meta";`);
  out = out.replace(/(FURNITURE_METAS: FurnitureMeta\[\] = \[[^\]]*)\]/, `$1, ${id}_META]`);
  out = out.replace(/(FURNITURE_LOADERS[^{]*\{[\s\S]*?)(\n\};)/,
    `$1\n  ${id}: () => import("./${id}").then((m) => m.${id}),$2`);
  if (!out.includes(`"./${id}"`)) throw new Error("furnitures.ts loader anchor not found");
  return out;
}
