/** Each action's instruction text. Cached: it walks every action and formats every instruction,
 *  which is wasted work to repeat on each spoken step.
 *
 *  It used to return a POSITION — the step's index in the deduped list — which is what tied the clip
 *  number to the app's action order. The text is what the recording is actually keyed on, so that is
 *  what this hands back now; BLOCKS does the numbering. */
//  KEYED ON THE FURNITURE OBJECT, not on its id. A `${id}:${level}` key meant two Furniture values
//  sharing an id shared one map — harmless in the app, where a model is loaded once, and a trap
//  anywhere a second one exists: a test standing up a small fixture under a real id would poison the
//  cache for the real content, and the real content would then report that half its steps have no
//  clip. A WeakMap also lets a swapped-out model be collected instead of pinning every furniture
//  ever loaded for the life of the process.
const lineCache = new WeakMap<Furniture, Map<TextLevel, Map<string, string>>>();

function lineTextFor(furniture: Furniture, level: TextLevel): Map<string, string> {
  let byLevel = lineCache.get(furniture);
  if (!byLevel) {
    byLevel = new Map();
    lineCache.set(furniture, byLevel);
  }
  const hit = byLevel.get(level);
  if (hit) return hit;

  const set = buildInstructions(
    furniture.actions,
    furniture.parts,
    furniture.labels,
    furniture.instructions ?? {},
    furniture.clusters ?? {},
  );
  // ACTION ORDER, first occurrence wins — the same walk the script did, so the positions agree.
  // No de-duplication step any more: repeated sentences simply map to the same text and therefore
  // to the same clip, which is what "Place the Leg into position." said four times always meant.
  const byAction = new Map<string, string>();
  for (const action of furniture.actions) {
    const text = instructionText(set, action.actionId, level);
    if (text) byAction.set(action.actionId, text);
  }
  byLevel.set(level, byAction);
  return byAction;
}

/**
 * The storage path for one step's recording, or null if there is no clip for it.
 *
 * Null covers a model with no recordings and an action that is not part of the build. Callers should
 * do what onboarding's speech does with a missing clip — fall back to synthesis rather than going
 * quiet, so a step is never silent just because a file is absent.
 */
export function stepVoicePath(
  furniture: Furniture,
  actionId: ActionId,
  level: TextLevel,
): string | null {
  const block = SCRIPT_BLOCKS[furniture.meta.id]?.[level];
  if (!block) return null;
  const text = lineTextFor(furniture, level).get(actionId);
  if (text === undefined) return null;
  // BY SENTENCE, not by position — see the note on BLOCKS. A step whose wording is no longer in the
  // block has no recording, and saying so is the point: the caller falls back to synthesis, which is
  // the honest outcome. Returning a neighbouring clip because it happens to sit at the same index is
  // the bug this replaced.
  const index = block.lines.indexOf(text);
  if (index < 0) return null;
  return `${block.folder}/${block.prefix}-${block.firstLine + index}.mp3`;
}