// Where each assembly step's recording lives in storage.
//
// THE NUMBER IS THE LINE NUMBER. The clips were cut from the generated script (one text file, all
// four models at both text levels), and each file is named for the line it came from — so
// `LACK-standard-11.mp3` is line 11 of that file, which is the first LACK standard instruction.
//
// That is why the numbers do not start at 1 and why they are not action indices. LACK has thirteen
// actions but only four distinct sentences, because "Place the Leg into position." is said for every
// leg; the script lists each sentence ONCE, so there are four clips and one of them plays four
// times.
//
// The mapping is BY SENTENCE: format the step's instruction, find that line in its block, and its
// position gives the file. It used to be by position in the app's own deduped list, which is what
// broke — see the note on BLOCKS below for what that cost and why the two orderings differ.
import type { ActionId, Furniture, TextLevel } from "@/src/game/core/type";
import { buildInstructions, instructionText } from "@/src/game/core/presentation/instructions";

export const VOICEOVER_BUCKET = "Voiceover";

/**
 * Folder, file prefix, and THE BLOCK'S LINES IN SCRIPT ORDER.
 *
 * WHY THE LINES ARE HERE AS TEXT rather than a starting number and a count. The clip number used to
 * be `offset + the step's position in the app's deduped list`, which assumes the script was written
 * in the same order the app walks its actions. It was not. The generator grouped its output BY KIND
 * — every placement, then the cluster beats, then every fastener pair — while a build interleaves
 * them, fastening each sub-assembly as it goes.
 *
 * Both orderings contain the same sentences and the same number of them, which is exactly why the
 * bug survived: every offset was right, every count matched the uploaded files, and every wrong
 * number still resolved to a real clip. Nothing 404'd, nothing fell back to synthesis. The build
 * simply narrated a different step from the one on screen.
 *
 * LACK and BEKVAM were unaffected, and only by luck: their builds place every part before fastening
 * anything, so the two orderings coincide. DALFRED diverged at its first screw (15 of 20 standard
 * lines wrong, 9 of 14 simple) and EKET at its first runner screw (22 of 44, and 16 of 35).
 *
 * So a clip number is now a property of THE SENTENCE, not of the step's position: find the line in
 * this list, and its index from `firstLine` is the file. That also removes the older failure mode —
 * re-wording one step used to shift every clip after it, silently. Now an edited sentence simply
 * stops matching, and `stepVoicePath` returns null so the step falls back to synthesis instead of
 * confidently speaking its neighbour. stepVoice.test.ts turns that into a failure at build time.
 *
 * THE TEXT IS THE APP'S OWN, not retyped from the script. Each block was generated by running the
 * instruction builder and re-sorting its output into the script's order, then checked to be a
 * permutation of it — same set, no duplicates. Verified against the live bucket on 24 Aug: all eight
 * blocks' first and last files return 200 and the numbers either side return 400, and all 113 files
 * across the four models are present.
 *
 * FOLDER AND PREFIX ARE SPELLED OUT, because storage is case-sensitive and the uploads follow no
 * single rule: LACK's folder is capitalised where the others are lowercase, its two blocks disagree
 * with each other ("LACK-standard-11.mp3" but "LACK-Simple-17.mp3"), and DALFRED is spelled
 * "dalferd". A derived path would produce the name the code thinks is right and get silence.
 */
